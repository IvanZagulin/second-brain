CRISIS_MARKERS = (
    "покончить с собой", "покончу с собой", "не хочу жить", "хочу умереть", "суицид", "убить себя",
    "самоповрежд", "порезать себя", "нет смысла жить", "лучше бы меня не было", "не вывожу совсем",
)


def crisis_signal(text: str) -> bool:
    low = text.lower()
    return any(m in low for m in CRISIS_MARKERS)
